-- ============================================================

create or replace function public.inventory_add(
    p_tote_id bigint,
    p_physical_release_id bigint,
    p_quantity integer default 1,
    p_notes text default null
)
returns public.inventory
language plpgsql
security definer
set search_path = ''
as $$
declare
    caller uuid;
    result public.inventory;
begin
    caller := private.require_active_user();

    if p_quantity <= 0 then
        raise exception 'Quantity must be greater than zero.';
    end if;

    if not exists (
        select 1 from public.totes where id = p_tote_id
    ) then
        raise exception 'Tote does not exist.';
    end if;

    if not exists (
        select 1
        from public.physical_releases
        where id = p_physical_release_id
    ) then
        raise exception 'Physical release does not exist.';
    end if;

    insert into public.inventory (
        tote_id,
        physical_release_id,
        quantity
    )
    values (
        p_tote_id,
        p_physical_release_id,
        p_quantity
    )
    on conflict (tote_id, physical_release_id)
    do update
    set quantity =
        public.inventory.quantity + excluded.quantity
    returning *
    into result;

    insert into public.inventory_transactions (
        transaction_type,
        physical_release_id,
        tote_id,
        quantity_delta,
        performed_by,
        notes
    )
    values (
        'inventory_add',
        p_physical_release_id,
        p_tote_id,
        p_quantity,
        caller,
        p_notes
    );

    return result;
end;
$$;

