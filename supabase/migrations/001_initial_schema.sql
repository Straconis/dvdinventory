create table public.inventory (
    id bigint generated by default as identity primary key,
    tote_id bigint not null
        references public.totes(id) on delete restrict,
    physical_release_id bigint not null
        references public.physical_releases(id) on delete restrict,
    quantity integer not null default 0 check (quantity >= 0),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (tote_id, physical_release_id)
);

create table public.checkouts (
    id bigint generated by default as identity primary key,
    physical_release_id bigint not null
        references public.physical_releases(id) on delete restrict,
    source_tote_id bigint not null
        references public.totes(id) on delete restrict,
    quantity integer not null check (quantity > 0),

    performed_by uuid references auth.users(id) on delete set null,
    checked_out_to text,
    destination text,
    notes text,
    checked_out_at timestamptz not null default now(),

    checked_in_at timestamptz,
    return_tote_id bigint
        references public.totes(id) on delete restrict,
    checked_in_by uuid references auth.users(id) on delete set null,

    status text not null default 'checked_out'
        check (status in ('checked_out','returned')),

    check (
        (
            status = 'checked_out'
            and checked_in_at is null
            and return_tote_id is null
            and checked_in_by is null
        )
        or
        (
            status = 'returned'
            and checked_in_at is not null
            and return_tote_id is not null
            and checked_in_by is not null
        )
    )
);

create table public.inventory_transactions (
    id bigint generated by default as identity primary key,

    transaction_type text not null check (
        transaction_type in (
