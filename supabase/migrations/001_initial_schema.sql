create or replace function public.inventory_transfer(
    p_source_tote_id bigint,
    p_destination_tote_id bigint,
    p_physical_release_id bigint,
    p_quantity integer default 1,
    p_notes text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    caller uuid;
    source_row public.inventory;
begin
    caller := private.require_active_user();

    if p_quantity <= 0 then
        raise exception 'Quantity must be greater than zero.';
    end if;

    if p_source_tote_id = p_destination_tote_id then
        raise exception 'Source and destination totes must differ.';
    end if;

    if not exists (
        select 1
        from public.totes
        where id = p_destination_tote_id
    ) then
        raise exception 'Destination tote does not exist.';
    end if;

    select *
    into source_row
    from public.inventory
    where tote_id = p_source_tote_id
      and physical_release_id = p_physical_release_id
    for update;

    if not found then
        raise exception 'Source inventory does not exist.';
    end if;

    if source_row.quantity < p_quantity then
        raise exception 'Insufficient inventory.';
    end if;

    update public.inventory
    set quantity = quantity - p_quantity
    where id = source_row.id;

    insert into public.inventory (
        tote_id,
        physical_release_id,
        quantity
    )
    values (
        p_destination_tote_id,
        p_physical_release_id,
        p_quantity
    )
    on conflict (tote_id, physical_release_id)
    do update
    set quantity =
        public.inventory.quantity + excluded.quantity;

    insert into public.inventory_transactions (
        transaction_type,
        physical_release_id,
        tote_id,
        quantity_delta,
        performed_by,
        notes
    )
    values
        (
            'transfer',
            p_physical_release_id,
            p_source_tote_id,
            -p_quantity,
            caller,
            p_notes
        ),
        (
            'transfer',
            p_physical_release_id,
            p_destination_tote_id,
            p_quantity,
            caller,
            p_notes
        );
end;
$$;

