create or replace function private.current_user_is_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and active = true
    );
$$;

create or replace function private.current_user_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles
        where id = auth.uid()
          and active = true
          and role = 'admin'
    );
$$;

create or replace function private.require_active_user()
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
    caller uuid;
begin
    caller := auth.uid();

    if caller is null then
        raise exception 'Authentication required.';
    end if;

    if not private.current_user_is_active() then
        raise exception 'Active account required.';
    end if;

    return caller;
end;
$$;

-- ============================================================
-- ADMIN PROFILE MANAGEMENT
-- ============================================================

create or replace function public.admin_update_user(
    target_user uuid,
    new_role text default null,
    new_active boolean default null
)
returns public.profiles
language plpgsql
security definer
set search_path = ''
as $$
declare
    caller uuid;
    old_profile public.profiles;
    result public.profiles;
    admin_count bigint;
begin
    caller := auth.uid();

    if caller is null then
        raise exception 'Authentication required.';
    end if;

    if not private.current_user_is_admin() then
        raise exception 'Administrator privileges required.';
    end if;

    -- Serialize administrator-state changes.
    perform pg_catalog.pg_advisory_xact_lock(1480941637);

    select *
    into old_profile
    from public.profiles
    where id = target_user
    for update;

    if not found then
        raise exception 'User does not exist.';
    end if;

    if new_role is not null
       and new_role not in ('user','admin') then
        raise exception 'Invalid role.';
    end if;

    if target_user = caller then
        if new_active is false then
            raise exception 'You cannot deactivate your own account.';
        end if;

        if new_role is not null
           and new_role <> old_profile.role then
            raise exception 'You cannot change your own administrator role.';
        end if;
    end if;

    if old_profile.role = 'admin'
       and old_profile.active = true
       and (
            new_role = 'user'
            or new_active is false
       ) then

        select count(*)
        into admin_count
        from public.profiles
        where role = 'admin'
          and active = true;

        if admin_count <= 1 then
            raise exception 'Cannot remove the final active administrator.';
        end if;
    end if;

    if new_role is not null
       and new_role <> old_profile.role then

        insert into public.user_admin_audit (
            target_user_id,
            target_username,
            action,
            old_value,
            new_value,
            performed_by
        )
        values (
            old_profile.id,
            old_profile.username,
            'role_changed',
            old_profile.role,
            new_role,
            caller
        );
    end if;

    if new_active is not null
       and new_active <> old_profile.active then

        insert into public.user_admin_audit (
            target_user_id,
            target_username,
            action,
            old_value,
            new_value,
            performed_by
        )
        values (
            old_profile.id,
            old_profile.username,
            case
                when new_active then 'user_activated'
                else 'user_deactivated'
            end,
            old_profile.active::text,
            new_active::text,
            caller
        );
    end if;

    update public.profiles
    set
        role = coalesce(new_role, role),
        active = coalesce(new_active, active)
    where id = target_user
    returning *
    into result;

    return result;
end;
$$;

