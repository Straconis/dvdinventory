-- ============================================================
-- CHECK IN
-- ============================================================

create or replace function public.checkin_inventory(
    p_checkout_id bigint,
    p_return_tote_id bigint,
    p_notes text default null
)
returns public.checkouts
language plpgsql
security definer
set search_path = ''
as $$
declare
    caller uuid;
    result public.checkouts;
begin
    caller := private.require_active_user();

    if not exists (
        select 1
        from public.totes
        where id = p_return_tote_id
    ) then
        raise exception 'Return tote does not exist.';
    end if;

    select *
    into result
    from public.checkouts
    where id = p_checkout_id
    for update;

    if not found then
        raise exception 'Checkout does not exist.';
    end if;

    if result.status <> 'checked_out' then
        raise exception 'Checkout has already been returned.';
    end if;

    insert into public.inventory (
        tote_id,
        physical_release_id,
        quantity
    )
    values (
        p_return_tote_id,
        result.physical_release_id,
        result.quantity
    )
    on conflict (tote_id, physical_release_id)
    do update
    set quantity =
        public.inventory.quantity + excluded.quantity;

    update public.checkouts
    set
        status = 'returned',
        checked_in_at = now(),
        return_tote_id = p_return_tote_id,
        checked_in_by = caller,
        notes = case
            when p_notes is null then notes
            when notes is null then p_notes
            else notes || E'\n' || p_notes
        end
    where id = p_checkout_id
    returning *
    into result;

    insert into public.inventory_transactions (
        transaction_type,
        physical_release_id,
        tote_id,
        quantity_delta,
        checkout_id,
        performed_by,
        notes
    )
    values (
        'checkin',
        result.physical_release_id,
        p_return_tote_id,
        result.quantity,
        result.id,
        caller,
        p_notes
    );

    return result;
end;
$$;

-- ============================================================
-- ADMIN INVENTORY CORRECTION
-- ============================================================

create or replace function public.admin_adjust_inventory(
    p_tote_id bigint,
    p_physical_release_id bigint,
    p_new_quantity integer,
    p_notes text
)
returns public.inventory
language plpgsql
security definer
set search_path = ''
as $$
declare
    caller uuid;
    old_row public.inventory;
    result public.inventory;
    delta integer;
begin
    caller := auth.uid();

    if caller is null then
        raise exception 'Authentication required.';
    end if;

    if not private.current_user_is_admin() then
        raise exception 'Administrator privileges required.';
    end if;

    if p_new_quantity < 0 then
        raise exception 'Quantity cannot be negative.';
    end if;

    if p_notes is null or length(trim(p_notes)) = 0 then
        raise exception 'Adjustment reason is required.';
    end if;

    if not exists (
        select 1 from public.totes where id = p_tote_id
    ) then
        raise exception 'Tote does not exist.';
    end if;

    if not exists (
        select 1
        from public.physical_releases
        where id = p_physical_release_id
    ) then
        raise exception 'Physical release does not exist.';
    end if;

    select *
    into old_row
    from public.inventory
    where tote_id = p_tote_id
      and physical_release_id = p_physical_release_id
    for update;

    if found then
        delta := p_new_quantity - old_row.quantity;

        update public.inventory
        set quantity = p_new_quantity
        where id = old_row.id
        returning *
        into result;
    else
        delta := p_new_quantity;

        insert into public.inventory (
            tote_id,
            physical_release_id,
            quantity
        )
        values (
            p_tote_id,
            p_physical_release_id,
            p_new_quantity
        )
        returning *
        into result;
    end if;

    if delta <> 0 then
        insert into public.inventory_transactions (
            transaction_type,
            physical_release_id,
            tote_id,
            quantity_delta,
            performed_by,
            notes
        )
        values (
            'adjustment',
            p_physical_release_id,
            p_tote_id,
            delta,
            caller,
            p_notes
        );
    end if;

    return result;
end;
$$;

