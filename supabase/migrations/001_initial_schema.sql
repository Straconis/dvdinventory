-- INVENTORY REMOVE
-- ============================================================

create or replace function public.inventory_remove(
    p_tote_id bigint,
    p_physical_release_id bigint,
    p_quantity integer default 1,
    p_notes text default null
)
returns public.inventory
language plpgsql
security definer
set search_path = ''
as $$
declare
    caller uuid;
    result public.inventory;
begin
    caller := private.require_active_user();

    if p_quantity <= 0 then
        raise exception 'Quantity must be greater than zero.';
    end if;

    select *
    into result
    from public.inventory
    where tote_id = p_tote_id
      and physical_release_id = p_physical_release_id
    for update;

    if not found then
        raise exception 'Inventory record does not exist.';
    end if;

    if result.quantity < p_quantity then
        raise exception 'Insufficient inventory.';
    end if;

    update public.inventory
    set quantity = quantity - p_quantity
    where id = result.id
    returning *
    into result;

    insert into public.inventory_transactions (
        transaction_type,
        physical_release_id,
        tote_id,
        quantity_delta,
        performed_by,
        notes
    )
    values (
        'inventory_remove',
        p_physical_release_id,
        p_tote_id,
        -p_quantity,
        caller,
        p_notes
    );

    return result;
end;
$$;

-- ============================================================
