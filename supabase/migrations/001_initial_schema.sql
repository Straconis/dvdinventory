-- ------------------------------------------------------------
-- Audit history
--
-- Users may read and insert history.
-- Existing history cannot be silently edited/deleted by normal users.
-- ------------------------------------------------------------

drop policy if exists "transactions_read"
on public.inventory_transactions;

create policy "transactions_read"
on public.inventory_transactions
for select
to authenticated
using (
    public.current_user_is_active()
);


drop policy if exists "transactions_insert"
on public.inventory_transactions;

create policy "transactions_insert"
on public.inventory_transactions
for insert
to authenticated
with check (
    public.current_user_is_active()
    and performed_by = auth.uid()
);


drop policy if exists "transactions_admin_update"
