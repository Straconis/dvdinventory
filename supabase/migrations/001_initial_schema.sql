    physical_release_id bigint not null
        references public.physical_releases(id) on delete restrict,

    tote_id bigint
        references public.totes(id) on delete restrict,

    quantity_delta integer not null,

    checkout_id bigint
        references public.checkouts(id) on delete set null,

    performed_by uuid
        references auth.users(id) on delete set null,

