    edition text,
    format text,
    region text,
    studio text,
    distributor text,
    release_year integer,
    release_date date,
    aspect_ratio text,
    disc_count integer,
    packaging text,
    asin text,
    cover_image_url text,
    notes text,

    metadata_status text not null default 'unknown'
        check (
            metadata_status in (
                'unknown',
                'incomplete',
                'enriched',
                'verified',
                'needs_review'
            )
